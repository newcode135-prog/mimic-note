const CATALOG = { ko, en, zh };

// tr('en').missionsOf('Minho') — 없는 언어·키는 한국어로
export function tr(lang) {
  const base = CATALOG[lang] || ko;
  return new Proxy(base, { get: (t, k) => (k in t ? t[k] : ko[k]) });
}

export const isLang = (x) => LANGS.includes(x);

// 텔레그램 앱 언어(from.language_code)로 처음 보는 사람의 언어를 짐작(연결 전 안내용)
export const guessLang = (code) => (/^zh/i.test(code || '') ? 'zh' : /^en/i.test(code || '') ? 'en' : 'ko');

// 이름 표시: 한국어는 명부의 한글 이름, 영어·중국어는 영문 아이디(첫 글자 대문자)
export const dn = (member, lang) => (!member ? '' : lang === 'en' || lang === 'zh' ? member.id.charAt(0).toUpperCase() + member.id.slice(1) : member.name);

// 모든 언어의 버튼 이름(봇이 받은 글이 어느 버튼인지 알아보는 데 씀)
export const allLabels = (key) => LANGS.map((l) => CATALOG[l][key] ?? ko[key]);
